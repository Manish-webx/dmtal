          <!-- Section: What Recovery Actually Looks Like -->
          <div class="mt-5 fade-up">
            <h2 class="lux-section-title">What Recovery Actually Looks Like</h2>
            <p>
              Initial healing takes about seven to ten days, during which small scabs form around each graft and
              gradually fall away as the skin settles. Redness and mild sensitivity in both the donor and beard area
              improve steadily through this period, and most patients are comfortable resuming normal routines shortly
              after.
            </p>
            <p>
              Somewhere between two and four weeks after the procedure, the newly transplanted hair typically sheds.
              This is expected and is not a sign that the transplant has failed, the hair follicle itself remains in
              place under the skin, only the visible hair shaft falls out temporarily before the follicle re-enters a
              new growth cycle. This shedding phase is the point where patients often worry the most, and it is worth
              knowing in advance that it is a completely normal part of the process, not a complication.
            </p>
            <p>
              New growth generally begins reappearing around three to five months post procedure, often looking fine and
              sparse at first before thickening. Visible, meaningful density is typically seen between six and nine
              months, with the fully mature final result taking up to twelve to eighteen months to settle completely,
              which is longer than most patients expect going in.
            </p>

