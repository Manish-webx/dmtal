            <h2 class="lux-section-title mt-4">What a Chemical Peel for Indian Skin Actually Does</h2>
            <h3 class="h5 fw-bold text-charcoal">The Science Behind Controlled Exfoliation</h3>
            <p>A chemical peel works by applying an acid solution to the skin at a specific concentration for a specific
              duration, causing controlled exfoliation of the outer skin layers. As the skin repairs itself, new
              collagen is stimulated, cell turnover accelerates, pigmentation is disrupted, and the skin surface that
              emerges is clearer, more even in tone, and smoother in texture.</p>
            <p>The key word is controlled. The concentration of acid, the pH of the solution, the duration of
              application, the preparation of the skin in the weeks before, and the aftercare protocol in the weeks
              following all determine whether the outcome is transformative or damaging. Change any one of these
              variables without clinical knowledge of what you are doing and the result changes significantly.</p>

            <div class="alert alert-info border-0 rounded-3 shadow-sm my-4">
              <i class="bi bi-info-circle me-2"></i> Deep rolling and icepick scars require different interventions,
