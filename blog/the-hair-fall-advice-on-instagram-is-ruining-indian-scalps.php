            <p>In my 11 years of practice, I have never seen more scalp damage than I see today. Most of it traces
              back
              to those 60-second Instagram reels where everyone seems to be a medical expert overnight, with zero
              qualification and millions of followers trusting them with their health.</p>

            <h2 class="lux-section-title mt-3">Instagram and Hair: Why This Is a Real Problem</h2>
            <p>Instagram's algorithm rewards dramatic before-and-after results. It does not reward clinical accuracy. A
              reel with two million views is not a clinical study. It is content that performed well.</p>
            <p>The problem is worse for Indian scalps specifically. We deal with hard water, humidity, high DHT
              sensitivity and dietary patterns that are very different from the Western scalps most of this content is
              made for. Generic advice from a creator in some random country or city does not translate to a scalp in
              Gurugram or Delhi. But nobody mentions that in the caption.</p>
            <p>By the time most patients reach my clinic, they have already tried six or seven Instagram-approved
              routines and caused real damage in the process.</p>

            <h2 class="lux-section-title mt-3">The Trends I See Causing Real Damage</h2>
            <p>These are not fringe trends. These are things I see the consequences of every single week in my clinic.
            </p>

            <h3 class="h5 fw-bold mt-3 text-charcoal">Over Oiling Hairs</h3>
            <p>Oiling is not bad. The way Instagram recommends it is. Leaving oil on your scalp overnight every night
              clogs the follicles and creates the perfect environment for Malassezia Furfur Yeast or the fungus
              responsible for dandruff and scalp inflammation. Patients come in with severe dandruff and flaking and
              cannot understand why because they have been "nourishing" their scalp for months. Oil belongs to the hair
              shaft and should not lie on the scalp overnight. And is recommended once or twice a week and properly
              washed off. That is it.</p>

            <h3 class="h5 fw-bold mt-3 text-charcoal">Onion Juice</h3>
            <p>One small study showed modest benefit from onion juice. Instagram turned it into a miracle cure. Raw
              onion juice is highly acidic and disrupts the scalp's natural pH. In people with sensitive scalps it
              causes contact dermatitis and irritation. And because of the smell, people end up washing their hair more
              aggressively and more frequently, which leads to more breakage. If onion juice worked the way it is
              claimed to, every dermatologist in the country would be prescribing it right? But we are not and there are
              valid reasons for it.</p>

            <h3 class="h5 fw-bold mt-3 text-charcoal">Biotin Megadosing</h3>
            <p>Biotin gummies are the most oversold supplement in the hair care space right now. The truth is that
              biotin deficiency causing hair fall is genuinely rare. Most Indians are not deficient. What nobody tells
              you is that excess biotin interferes with thyroid and hormone lab results, which are the actual tests
              needed to find out why your hair is falling. Patients come to me for bloodwork and the results are skewed
              because of OTC biotin they have been taking for months. This delays the real diagnosis. And those months
              matter more than people realise.</p>
            <p>The gummies themselves are another marketing masterclass. They are sold like candy, packed with
              sweeteners and attractive packaging, and promoted as if healthy hair comes from chewing a bear-shaped
              supplement every morning. Meanwhile, the real reason for the hair fall could be iron deficiency, low
              Vitamin D levels, thyroid dysfunction, PCOS, or sometimes a combination of several factors. While people
              focus on gummies, these underlying causes often remain completely undiagnosed. Hair follicles do not care
              how good the packaging looks. They care whether the body has what it needs to grow healthy hair.</p>

            <h3 class="h5 fw-bold mt-3 text-charcoal">Scalp Scrubs</h3>
            <p>The scalp is not your face. It does not need a weekly physical scrub. Physical exfoliation on an already
              sensitive or inflamed scalp causes microtears and damages the follicle environment. If you already have
              seborrheic dermatitis or any underlying scalp condition, a scrub will make it significantly worse. The
              people selling these products will not tell you that.</p>

            <h3 class="h5 fw-bold mt-3 text-charcoal">Rosemary Oil as a DHT Blocker</h3>
            <p>Yes, one study did compare rosemary oil to minoxidil 2% and showed some results. What Instagram
              consistently forgets to mention is that the study involved six months of controlled application at a
              specific concentration. Randomly applying rosemary oil from a grocery store bottle is not the same thing.
              It is not a DHT blocker. And while people spend months trying it, the actual underlying cause whether
              hormonal, nutritional or genetic goes completely untreated.</p>

