            <h3 class="h5 fw-bold mt-4 text-charcoal">What to Ask Before Any Botox Procedure</h3>
            <p>A drooping eyelid, asymmetry or an unnatural result needs to be managed by someone with the clinical
              knowledge to assess what happened and the tools to address it. Asking what the follow up protocol is, and
              what happens if the result is not as expected, before committing to a procedure tells you a great deal
