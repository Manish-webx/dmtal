                <p class="text-muted mb-4">What cannot be changed is the fundamental skin type. What can be improved is
                  the degree of visible pigmentation, the unevenness of tone, and the overall appearance of the lips.
                  Understanding this distinction before starting treatment is what separates a satisfied patient from a
                  disappointed one.</p>
