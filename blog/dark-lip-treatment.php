              <div class="mt-4 mb-4">
                <h3 class="h4 fw-bold mb-3" style="color: #1B2A4A;">
                  <i class="bi bi-sun-fill me-2" style="color: #c97a63;"></i>Cause 1: Sun Damage and UV Induced Lip
                  Pigmentation
                </h3>
                <p class="text-muted">The lips have very little melanin protection compared to the rest of the face. The
                  lip skin is thin, has almost no sebaceous glands, and is directly exposed to UV radiation every single
                  day. In India, where UV intensity is high year round, cumulative sun damage is one of the most common
                  and most overlooked causes of progressive lip darkening.</p>
                <p class="text-muted mb-4">This type of lip pigmentation tends to worsen gradually over years, is more
                  pronounced on the upper lip which receives more direct sun exposure, and often presents as an uneven
                  brownish darkening that is more visible in summer. Most patients never connect their darkening lips to
                  sun exposure because nobody applies SPF to their lips. Sunscreen on the lips is not a common habit in
                  India and the cumulative damage from this gap shows up over time.</p>
              </div>

              <div class="mb-4">
                <h3 class="h4 fw-bold mb-3" style="color: #1B2A4A;">
                  <i class="bi bi-exclamation-octagon-fill me-2" style="color: #c97a63;"></i>Cause 2: Post Inflammatory
                  Hyperpigmentation from Habits and Products
                </h3>
                <p class="text-muted">This is the cause that surprises most patients. Repeated minor trauma to the lip
                  skin triggers melanin production in the same way any skin inflammation does. The habits driving this
                  are
                  so routine that nobody questions them.</p>
                <p class="text-muted">Licking the lips repeatedly, especially in dry weather, creates a cycle of
                  moisture
                  followed by rapid evaporation that causes chronic low grade irritation. Picking at dry or peeling lip
                  skin causes direct trauma. Certain lip products including heavily fragranced lip balms, lipsticks with
                  chemical irritants and even some matte formulas cause contact dermatitis in the lip skin that shows up
                  as progressive darkening over months.</p>
                <p class="text-muted mb-4">The patients who come to me with darkening specifically along the lip edges
                  or
                  in patches rather than uniformly across the lips almost always have this type of pigmentation. And
                  almost all of them are using a lip product that is contributing to it without realising it.</p>
              </div>

              <div class="mb-4">
                <h3 class="h4 fw-bold mb-3" style="color: #1B2A4A;">
                  <i class="bi bi-heart-pulse-fill me-2" style="color: #c97a63;"></i>Cause 3: Hormonal and Nutritional
                  Causes of Dark Lips
                </h3>
                <p class="text-muted">Hormonal fluctuations, particularly those associated with PCOS, thyroid
                  dysfunction
                  and pregnancy, can trigger melanin overproduction in the lip skin just as they do elsewhere on the
                  face.
                  This type of lip pigmentation often appears or worsens during specific life phases and tends to be
                  more
                  diffuse and uniform in appearance.</p>
                <p class="text-muted mb-4">Nutritional deficiencies, particularly vitamin B12 and iron deficiency, are
                  consistently associated with increased lip pigmentation in Indian patients. Both are common in the
                  Indian population due to dietary patterns. B12 deficiency specifically causes a characteristic
                  darkening
                  of the lips and surrounding skin that does not respond to topical treatment because the cause is
                  internal. Treating the deficiency is the treatment.</p>
              </div>

              <div class="mb-4">
                <h3 class="h4 fw-bold mb-3" style="color: #1B2A4A;">
                  <i class="bi bi-dna me-2" style="color: #c97a63;"></i>Cause 4: Genetic Lip Pigmentation: What Is and
                  Is
                  Not Changeable
                </h3>
                <p class="text-muted">Some degree of lip pigmentation in Indian skin is simply genetic. Darker natural
                  lip
                  colour is a normal characteristic of higher Fitzpatrick skin types and is not a pathological
