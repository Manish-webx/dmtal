                  <p class="mb-0 text-muted" style="font-size: 0.98rem; line-height: 1.7;">
                    The same review notes that a previous suntan noticeably raises the risk of burns and pigmentation after lasers. It also emphasizes that evidence in darker skin is thinner than it should be because many studies are small and skin types IV to VI remain underrepresented in global research.
                  </p>
