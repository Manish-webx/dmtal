            <h2 class="lux-section-title mt-2">Why Does Indian Skin Need a Longer Bridal Skin Prep Timeline?</h2>
            <p>
              Darker skin types (Fitzpatrick IV to VI) have more active melanocytes, so inflammation of any kind—including from a chemical peel, an energetic laser, or a minor micro-injury—can leave persistent pigmentation behind.
            </p>
            <p>
              A 2026 clinical review in <em>Plastic and Reconstructive Surgery Global Open</em> found that the greatest risk after chemical peels in these skin types is <strong>post-inflammatory hyperpigmentation (PIH)</strong>. It typically presents <strong>3 to 6 weeks</strong> after the peel, and early clinical management gives significantly better outcomes.
            </p>

            <div class="alert alert-info border-0 rounded-4 shadow-sm my-4 p-4" style="background-color: #f3f8fd; border-left: 4px solid #3b82f6 !important;">
