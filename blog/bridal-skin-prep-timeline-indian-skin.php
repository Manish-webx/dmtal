                    Natural henna paste rarely causes allergies. "Black henna" usually contains paraphenylenediamine (PPD) at concentrations of 15 to 30 percent in illicit cones. It causes severe allergic contact dermatitis <strong>7 to 14 days after first exposure</strong>, directly in the shape of the bridal pattern, leaving blisters and scarring. Always ask your mehendi artist what is in the cone and insist on 100% natural herbal henna.
