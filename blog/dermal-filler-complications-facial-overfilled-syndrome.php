                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    Most hyaluronic acid fillers last nine to eighteen months depending on the area treated, the specific product used, and the individual patient's metabolism. High movement areas like the lips metabolise filler faster than lower movement areas like the cheeks or jawline. Biostimulatory fillers like Sculptra last longer, typically two to three years, because they work by stimulating collagen rather than directly adding volume. Individual results vary and maintenance sessions are needed to sustain the result as the product gradually breaks down.
                  </div>
                </div>
              </div>

              <!-- FAQ 3 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingThree">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseThree" aria-expanded="false" aria-controls="collapseThree">
                    Why do some people look natural with fillers and others look overdone?
                  </button>
                </h3>
                <div id="collapseThree" class="accordion-collapse collapse" aria-labelledby="headingThree"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    The difference is almost never the product. It comes down to whether the injector matched the product to the area, used a conservative volume relative to the patient's existing facial structure, respected natural asymmetry rather than treating it as a flaw, and assessed cumulative volume across multiple sessions. A face that has received appropriate volume in the right anatomical planes looks rested and natural. A face that has received excess volume, product in the wrong depth, or accumulated filler from sessions that were never reassessed collectively looks done. The same product used by two different injectors on two different patients produces completely different outcomes.
                  </div>
                </div>
              </div>

              <!-- FAQ 4 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingFour">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseFour" aria-expanded="false" aria-controls="collapseFour">
                    What is filler migration and how does it happen?
                  </button>
                </h3>
                <div id="collapseFour" class="accordion-collapse collapse" aria-labelledby="headingFour"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    Filler migration occurs when product moves from the original injection site to surrounding tissue over time. It most commonly happens when filler is placed too superficially, when too much product is injected into an area that cannot accommodate it, or when the wrong product is used in an area with significant facial movement. It typically presents as a visible ridge, bump or contour irregularity that was not present immediately after treatment. Migration is one of the more challenging filler complications to manage as it often requires full dissolution before replanning rather than a simple correction.
                  </div>
                </div>
              </div>

              <!-- FAQ 5 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingFive">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseFive" aria-expanded="false" aria-controls="collapseFive">
                    How many syringes of filler do I actually need?
                  </button>
                </h3>
                <div id="collapseFive" class="accordion-collapse collapse" aria-labelledby="headingFive"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    This varies significantly based on the area being treated, the degree of volume loss present, and the individual facial structure. A single syringe divided across multiple areas is appropriate for many patients, particularly those seeking subtle enhancement or preventive treatment in their thirties. Significant volume restoration in a patient with substantial age-related changes may require two to three syringes across different areas. The number should be determined by clinical assessment of what is actually needed, not by a standard package or a generic recommendation. Starting with less and reviewing is always the safer approach.
                  </div>
                </div>
              </div>

              <!-- FAQ 6 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingSix">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseSix" aria-expanded="false" aria-controls="collapseSix">
                    What happens when you stop getting dermal fillers?
                  </button>
                </h3>
                <div id="collapseSix" class="accordion-collapse collapse" aria-labelledby="headingSix"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    The face gradually returns to how it would have looked without treatment as the product metabolises naturally. There is no rebound effect, no accelerated ageing, and no evidence that stopping fillers makes the face look worse than it would have looked without any filler at all. This is a common concern among patients who worry about dependency. The face simply ages at its natural rate once the filler has metabolised, which is the same rate it would have aged without treatment.
                  </div>
                </div>
              </div>

              <!-- FAQ 7 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingSeven">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseSeven" aria-expanded="false" aria-controls="collapseSeven">
                    Dermal fillers vs Botox, which should I choose?
                  </button>
                </h3>
                <div id="collapseSeven" class="accordion-collapse collapse" aria-labelledby="headingSeven"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    They address different concerns and are not interchangeable. Botox relaxes the muscles that cause dynamic wrinkles, the lines that appear with movement like frowning or squinting. Fillers restore volume that has been lost with age or add structure where it is naturally lacking. Many patients benefit from both, used in combination to address both dynamic lines and volume loss simultaneously. The right choice depends on what is actually driving the concern. Volume loss in the cheeks needs filler. Frown lines between the brows need Botox. A comprehensive assessment determines what is actually causing what the patient sees, which is why a treatment consultation rather than a treatment booking is the appropriate starting point.
                  </div>
                </div>
              </div>

              <!-- FAQ 8 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingEight">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseEight" aria-expanded="false" aria-controls="collapseEight">
                    How long does post filler swelling last?
                  </button>
                </h3>
                <div id="collapseEight" class="accordion-collapse collapse" aria-labelledby="headingEight"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    Mild swelling immediately after filler is normal and expected. In most areas it settles within twenty four to seventy two hours. The lips tend to swell more than other areas and may take up to a week to fully settle. Bruising, if it occurs, typically resolves within seven to ten days. The final result should be assessed at the two week mark when all swelling has fully resolved and the product has integrated into surrounding tissue. Any result that still looks heavy or uneven at two weeks deserves a follow up conversation, not additional waiting.
                  </div>
                </div>
              </div>

              <!-- FAQ 9 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingNine">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseNine" aria-expanded="false" aria-controls="collapseNine">
                    Is it too early for filler in your twenties or early thirties?
                  </button>
                </h3>
                <div id="collapseNine" class="accordion-collapse collapse" aria-labelledby="headingNine"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    No, but the approach needs to be calibrated to what is actually present. In the twenties and early thirties, significant volume loss is rarely the issue. The appropriate use of filler at this stage is subtle structural enhancement or very conservative volume maintenance in areas showing early change. The volume used should be significantly smaller than what would be appropriate for a patient in their forties or fifties with established volume loss. Starting conservatively and adding incrementally over years is the approach that produces natural results that age well, rather than an accelerated accumulation of product that becomes difficult to manage over time.
                  </div>
                </div>
              </div>

              <!-- FAQ 10 -->
              <div class="accordion-item mb-3 border-0 rounded-3 shadow-sm overflow-hidden">
                <h3 class="accordion-header" id="headingTen">
                  <button class="accordion-button collapsed fw-bold" type="button" data-bs-toggle="collapse"
                    data-bs-target="#collapseTen" aria-expanded="false" aria-controls="collapseTen">
                    What is the difference between hyaluronic acid fillers and other filler types?
                  </button>
                </h3>
                <div id="collapseTen" class="accordion-collapse collapse" aria-labelledby="headingTen"
                  data-bs-parent="#faqAccordion">
                  <div class="accordion-body text-muted" style="line-height: 1.7;">
                    Hyaluronic acid fillers are water attracting gels that add volume directly and are fully reversible with hyaluronidase. They are the most widely used and studied filler category. Biostimulatory fillers including Sculptra and Radiesse work differently, stimulating the body's own collagen production rather than directly adding volume. Results from biostimulatory fillers develop gradually over months and last longer than hyaluronic acid fillers, but they cannot be dissolved if the result is unsatisfactory. The choice between them depends on the specific concern, the area being treated, and what outcome the patient is seeking.
                  </div>
