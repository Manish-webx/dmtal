                    Midface structure, soft tissue thickness and baseline cheek volume differ significantly across ethnicities. Much of the dosing protocol used globally is built around Western facial proportions. Applying that template without adjustment to an Indian face that already has fuller, softer baseline cheek structure is one of the most common and least discussed reasons filler results in India look heavier than the international reference photos patients come in holding.
