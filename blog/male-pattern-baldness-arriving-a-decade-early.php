            <p>
              Around <strong>25 percent</strong> of men with male pattern baldness begin losing hair before the age of 21. By 35, roughly two out of every three men will have some visible thinning. By 50, that figure rises to about 85 percent. Studies looking specifically at younger men have found that as many as 16 percent of men between 18 and 29 already show signs of it, compared to over half of men in their forties.
            </p>

