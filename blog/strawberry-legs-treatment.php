            <h2 class="lux-section-title mt-4">What Are Strawberry Legs and Why Do You Have Them</h2>
            <p>Strawberry legs is the name given to the small dark dots and rough bumpy texture that appear on legs and
              give the skin a speckled appearance similar to the surface of a strawberry. It is not a single diagnosis.
              It is a visible result that can come from four completely different underlying causes. Identifying which
              one is driving the appearance changes everything about what will and will not work.</p>

            <h2 class="lux-section-title mt-4">The Four Causes of Strawberry Legs Most People Never Know About</h2>
            <p>Most patients have never heard these four categories explained. Which is exactly why they keep trying the
              same approaches and getting the same result.</p>

            <div class="row justify-content-center my-5">
              <div class="col-lg-10">
                <img src="blog-thumb/strawberry-legs-infographic.jpg" 
