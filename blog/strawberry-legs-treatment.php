                     alt="Infographic detailing the 4 main causes of Strawberry Legs: 1. Oxidised Sebum (blocked pores with trapped oil and dead skin), 2. Keratosis Pilaris (keratin protein buildup causing rough bumps), 3. Folliculitis (inflammation or infection of hair follicles), and 4. Ingrown Hairs (hairs curling back into the skin).">
              </div>
            </div>

            <div class="mt-5 mb-4">
              <h3 class="h4 fw-bold mb-3" style="color: #d64a4a;"><i class="bi bi-exclamation-triangle-fill me-2"></i>Why Everything You Have Tried for Strawberry Legs Has Made It Worse</h3>
              <p class="text-muted">If your strawberry legs appear or worsen after shaving, folliculitis and ingrown hairs are almost
                certainly involved. A blunt razor drags across the skin rather than cutting cleanly, irritating every
                follicle it passes over. Dry shaving without any buffer between the blade and skin causes the same damage.
                Shaving against the direction of hair growth makes it significantly worse because it cuts the hair at an
                angle that makes it more likely to curl back into the skin.</p>
              <p class="text-muted mb-4">The irritation triggers inflammation. The inflammation in Indian skin triggers melanin production. The
                dark spots that result are not from the hair itself; they are post-inflammatory hyperpigmentation, and
                they do not fade quickly on their own.</p>

              <h4 class="h5 fw-bold mt-4 text-dark"><i class="bi bi-x-circle-fill text-danger me-2 opacity-75"></i>Why Over Exfoliating Is Making Your Strawberry Legs Worse</h4>
              <p class="text-muted mb-4">Physical scrubbing does not reach inside the follicle where the problem is. It irritates the skin
                surface, triggers more inflammation, and in Indian skin triggers more melanin production. The dark spots
                get darker, not lighter.</p>

              <h4 class="h5 fw-bold mt-4 text-dark"><i class="bi bi-x-circle-fill text-danger me-2 opacity-75"></i>Why Moisturisers and Oils Do Not Fix Strawberry Legs</h4>
              <p class="text-muted mb-0">Keeping skin moisturised helps with the dryness that can worsen keratosis pilaris. But coconut oil,
                almond oil and the various body oils recommended online are occlusive; they sit on the skin surface. They
                do not reach inside congested follicles and can actually worsen follicle congestion by adding more oil on
                top of pores that are already blocked.</p>
            </div>

            <h2 class="lux-section-title mt-4">Strawberry Legs on Dark Indian Skin: Why the Treatment Needs to Be
              Different</h2>
            <p>Indian skin sits between Fitzpatrick Type III and V. This matters enormously for how strawberry legs
              present and how it should be treated.</p>
            <p>Higher melanin density means that any inflammation from shaving irritation, from scrubbing, from
              folliculitis, from an ingrown hair triggers a stronger and more lasting pigmentation response than in
              lighter skin types. The dark spots that result are post inflammatory hyperpigmentation, and they persist
              significantly longer in Indian skin than in Caucasian skin.</p>
            <p>This is why the same scrubbing routine that improves the appearance of strawberry legs in someone with
              Fitzpatrick Type I or II skin can actively worsen the dark spots in Indian skin. It is also why the
              treatment approach needs to be calibrated specifically for Indian skin rather than copied from Western
              skincare content, which makes up the vast majority of what is written about this topic online.</p>

