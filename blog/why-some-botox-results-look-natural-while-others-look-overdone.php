              <h3 class="h5 fw-bold text-charcoal mb-2">The Face at Rest</h3>
              <p class="mb-0 text-muted">
                Where do the brows naturally sit? Is there existing asymmetry? Some degree of facial asymmetry is normal
                in almost everyone, and treating both sides identically when they are not identical is one of the most
                common causes of an "off" looking result.
              </p>
            </div>

            <div class="clinical-cause-card">
              <span
