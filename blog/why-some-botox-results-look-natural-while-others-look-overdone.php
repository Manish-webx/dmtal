              <h3 class="h5 fw-bold text-charcoal mb-2">Brow Shape and Forehead Height</h3>
              <p class="mb-0 text-muted">
                A short forehead does not tolerate the same dosing pattern as a tall one. Ignore this and you get the
                flat, heavy brow that reads instantly as "done."
              </p>
            </div>

            <p>
              Skipping this step and defaulting to a standard unit count for every patient is, in my experience, the
              single biggest reason Botox results look frozen rather than natural.
            </p>

            <!-- SECTION 3 -->
            <h2 class="lux-section-title mt-2">Why "Standard Units" Is the Wrong Way to Think About Dosing</h2>
            <p>
              A lot of clinics quote Botox by a flat per-area price—"forehead: X units, glabella: Y units"—regardless of
              who is sitting in the chair. This is administratively convenient. It is not clinically sound.
            </p>
            <p>
              Muscle strength varies significantly between individuals, and even more significantly between men and
              women. A patient with a strong frontalis muscle who is under-dosed will barely see a change and may come
              back disappointed. A patient with a naturally weaker frontalis who receives the same "standard" dose can
              end up with a forehead that cannot move at all—the classic frozen look.
            </p>
            <p>
              Dosing should be a range, calibrated to what your muscle actually does in front of the injector, not a
              fixed number applied uniformly. This is also why the same patient's ideal dose often changes slightly
              session to session, depending on muscle response from the previous treatment.
            </p>

            <!-- SECTION 4 -->
            <h2 class="lux-section-title mt-2">Placement Precision: Why Two Injectors Using the Same Units Get Different
              Results</h2>
            <p>
              Even with the right total dose, where it goes matters as much as how much. Botox needs to be placed at
              specific depths and specific points relative to the muscle's motor points—the spots where the nerve signal
              actually enters the muscle. Injecting slightly too high, too low, or too close to the brow can:
            </p>
            <ul class="mb-4" style="line-height: 1.8;">
              <li><strong>Drop the brow</strong> instead of softening the forehead (brow ptosis)</li>
              <li><strong>Create an unnatural arch or "Spock brow"</strong> where the outer brow sits unnaturally high
                while the middle stays immobile</li>
              <li><strong>Cause asymmetric movement</strong> that wasn't there before treatment</li>
            </ul>
            <p>
              This is technical, hands-on skill that develops with experience and repetition, not something that scales
              evenly across every provider offering the treatment. It's a large part of why dermatologist-administered
              Botox—where facial anatomy is a core clinical competency rather than an add-on skill—tends to produce more
              consistently natural results.
            </p>

