            <h2 class="lux-section-title mt-2">The Anatomy Assessment Most Clinics Skip</h2>
            <p>
              A proper Botox consultation is not "how many units do you want." It is a comprehensive facial movement
              assessment. Before I inject anything, I need to evaluate:
            </p>

