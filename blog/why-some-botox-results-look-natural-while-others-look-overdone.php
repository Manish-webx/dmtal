              <h3 class="h5 fw-bold text-charcoal mb-2">The Face in Motion</h3>
              <p class="mb-0 text-muted">
                I ask patients to raise their eyebrows, frown, and scrunch their eyes. This shows me exactly which
                muscle fibres are doing the work, how strong they are, and how they interact with neighbouring muscles
                that are not being treated. A strong frontalis (forehead muscle) paired with a weak brow depressor, for
                instance, needs a completely different unit distribution than the reverse.
              </p>
            </div>

            <div class="clinical-cause-card">
              <span
                class="badge bg-warning bg-opacity-10 text-warning-emphasis fw-bold px-3 py-1 rounded-pill mb-2 text-uppercase"
