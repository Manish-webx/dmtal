            <h2 class="lux-section-title mt-4">Why Acne Scars Are Not a Surface Problem</h2>
            <h3 class="h5 fw-bold mt-3 text-charcoal">What Is Actually Happening Under the Skin</h3>
            <p>When a pimple becomes deeply inflamed, the inflammation damages the collagen and tissue structure
              underneath the skin. When the body repairs that damage, it does not always do it cleanly. Sometimes it
              produces too little collagen and leaves a depressed scar. Sometimes too much and leaves a raised one.</p>
            <p>The dark marks that remain after a pimple heals are a different story. <a
                href="https://www.dermatales.com/pigmentation-treatment-in-gurgaon"
                style="text-decoration: underline;">Post inflammatory hyperpigmentation</a> is a pigmentation response
              triggered by the inflammation. It is not a structural scar. It behaves differently, responds to different
              treatments, and fades at a different rate.</p>
            <p>Most people treat both the same way. That is the first mistake.</p>
            <p>In my experience, roughly 7 out of 10 patients who come to me frustrated that their acne scar treatment
              is not working have been using the wrong approach for the wrong type of scarring. Not because they did not
              try. Because nobody mapped their scars properly before recommending a treatment.</p>

            <h2 class="lux-section-title mt-4">Why the Type of Scar Changes Everything</h2>

            <h3 class="h5 fw-bold mt-3 text-charcoal">Post Inflammatory Hyperpigmentation</h3>
            <p>Flat dark marks left after acne are not structural scars. They are pigmentation changes. They respond
              well to topical actives like tranexamic acid, azelaic acid and retinoids combined with non-negotiable
              daily sunscreen. Given the right approach and enough time, most of them fade significantly.</p>
            <p>The mistake I see most often here is patients using the wrong actives or skipping sunscreen. UV exposure
              keeps triggering new pigmentation faster than any treatment can fade the existing marks. The treatment is
              not failing. The sun exposure is undoing it. If you have been struggling with persistent dark patches,
              understanding <a href="blog/what-your-dermatologist-is-not-telling-you-about-pigmentation-treatment"
                style="text-decoration: underline;">why your dark spots keep returning</a> is essential before adding
              more actives to your routine.</p>

