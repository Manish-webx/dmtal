                  <p class="mb-0 text-muted" style="font-size: 0.98rem; line-height: 1.7;">
                    I could not find a randomised trial that compares peel or laser outcomes by season. This advice rests on how pigment responds to sun and on clinical practice, not on a head-to-head study.
                  </p>
