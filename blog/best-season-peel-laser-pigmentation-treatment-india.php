            <!-- SECTION 2 -->
            <h2 class="lux-section-title mt-2">Why Does Sun Decide the Outcome?</h2>
            <p>
              Sun exposure is the most important trigger for melasma, according to a clinical and epidemiological review. Melasma usually improves in winter and worsens in summer, and that review reports high protection sunscreen reduced its intensity by about 50 percent in the studies it cites.
            </p>
            <p>
              The <strong>Indian Pigmentary Expert Group</strong> consensus says both UV and visible light are involved in melasma, and that sunscreen should be prescribed to every melasma patient. In a randomised study, daily high protection sunscreen prevented melasma recurrence even in summer.
            </p>
            <p>
              For treatments, a 2026 review of darker skin types (Fitzpatrick IV to VI) found that pigmentation after a chemical peel typically presents <strong>3 to 6 weeks later</strong>, and that a previous suntan raises the risk after lasers. That 3 to 6 week delay is why the calendar matters.
            </p>

