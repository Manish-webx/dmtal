            <!-- SECTION 2 -->
            <h2 class="lux-section-title mt-2">Why Does Dandruff Get Worse in Winter?</h2>
            <p>
              The American Academy of Dermatology notes that seborrheic dermatitis flare-ups are inherently seasonal, with the vast majority occurring during <strong>winter and early spring</strong>, often clearing spontaneously during warm, humid summer weather.
            </p>
            <p>
              It lists <strong>hot showers in cold, dry weather</strong> as the most pervasive trigger. In winter, ambient indoor heating and biting outdoor winds strip natural epidermal moisture. Standing under steaming hot water further melts away essential scalp lipids, causing acute barrier compromise. Alcohol-based hair sprays, styling gels, and elevated year-end stress are well-documented co-triggers.
            </p>
            <p>
              Mayo Clinic adds that seborrheic dermatitis frequently flares in response to physical fatigue, psychological stress, and seasonal transition. While the exact immunological mechanism remains under active investigation, a lipophilic yeast called <em>Malassezia</em> (which normally colonizes all human scalps) feeds on sebum triglycerides, breaking them down into irritating oleic fatty acids that trigger inflammation when the scalp barrier is weakened by winter weather.
            </p>

            <!-- SECTION 3 -->
            <h2 class="lux-section-title mt-2">Is It Dandruff or Scalp Psoriasis?</h2>
            <p>
              Dandruff flakes are characteristically softer, white-to-yellowish, and slightly greasy to the touch, sitting over mildly erythematous scalp tissue.
            </p>
            <p>
              In contrast, <strong>scalp psoriasis</strong> is an autoimmune-mediated condition characterized by accelerated epidermal turnover. Keratinocytes multiply up to ten times faster than normal, building up into thick, dry, silvery-white micaceous scales over well-defined, palpable plaques. These plaques routinely breach the hairline, creeping onto the forehead, the back of the neck, or around the earlobes. Scalp psoriasis does not usually cause permanent hair loss, but intense scratching can traumatize follicles.
            </p>
            <p>
              Because the visual signs overlap, attempting to guess at home often leads to months of using the wrong product—such as applying harsh drying anti-dandruff formulas to an already distressed psoriatic plaque. A dermatologist can distinguish them within minutes through dermoscopy.
            </p>

