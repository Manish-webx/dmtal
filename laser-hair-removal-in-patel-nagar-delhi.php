          <div class="mt-5 fade-up">
            <h2 class="lux-section-title">What Is Laser Hair Removal — And Is It Actually Permanent?</h2>
            <p>
              Laser hair removal works by targeting melanin (the pigment) inside the hair follicle with concentrated
              light energy. The heat from this light destroys the follicle's ability to produce new hair — without
              damaging the surrounding skin.
            </p>
            <p>
              The key word most clinics use is <strong>'permanent hair reduction'</strong>, not 'permanent hair
              removal'. This is medically accurate. In most patients, laser treatment achieves a 70 to 90% reduction in
              hair density after a full course of sessions. The remaining hair is typically finer, lighter, and sparser.
              For most people, this is more than enough — and occasional maintenance sessions keep it that way.
            </p>
            <p>
              <strong>Why can't it be 100% permanent?</strong> Hair grows in cycles — anagen (active), catagen
              (transition), and telogen (resting). Laser only affects follicles in the active anagen phase. This is why
              multiple sessions spaced 4 to 6 weeks apart are needed — each session catches a fresh batch of follicles
              entering the active phase.
            </p>
          </div>

