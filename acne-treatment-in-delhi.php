            <p>
              Most acne begins with a blocked pore, oil and dead skin cells trapping bacteria beneath the surface, which is why comedonal acne, blackheads and whiteheads responds well to topical treatment alone. Inflammatory and cystic acne go a step further, with deeper bacterial involvement and inflammation that sits below the skin and often needs an oral medication to control from the inside.
