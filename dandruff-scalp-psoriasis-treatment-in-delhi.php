                  </button>
                </h3>
                <div id="sfaq5" class="accordion-collapse collapse" data-bs-parent="#scalpFAQ">
                  <div class="accordion-body faq-body">
                    Yes, stress is a well recognized trigger for psoriasis flares, alongside seasonal changes, certain infections, and some medications. Identifying your personal triggers is a genuine part of managing the condition long term, not just treating flares as they happen.
                  </div>
                </div>
