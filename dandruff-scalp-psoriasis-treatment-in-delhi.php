                <h3 class="accordion-header">
                  <button class="accordion-button faq-button" type="button" data-bs-toggle="collapse"
                    data-bs-target="#sfaq1">
                    What's the actual difference between dandruff and scalp psoriasis?
                  </button>
                </h3>
                <div id="sfaq1" class="accordion-collapse collapse show" data-bs-parent="#scalpFAQ">
                  <div class="accordion-body faq-body">
                    Dandruff comes from an overgrowth of yeast naturally present on the scalp, producing mild flakes without much redness. Scalp psoriasis is an autoimmune condition causing thick, silvery plaques that can bleed if scratched and often affects other areas of the body, which is why it needs a different treatment approach entirely.
                  </div>
                </div>
              </div>

              <div class="accordion-item faq-item">
                <h3 class="accordion-header">
                  <button class="accordion-button collapsed faq-button" type="button" data-bs-toggle="collapse"
                    data-bs-target="#sfaq2">
                    How can I tell if my scalp condition is fungal or psoriasis?
                  </button>
                </h3>
                <div id="sfaq2" class="accordion-collapse collapse" data-bs-parent="#scalpFAQ">
                  <div class="accordion-body faq-body">
                    Dandruff and seborrheic dermatitis, both linked to yeast, tend to cause finer, sometimes greasy flakes without thick buildup. Scalp psoriasis produces noticeably thicker, more defined plaques that can bleed when picked, and often shows up alongside nail changes or patches elsewhere on the body. A proper scalp examination gives a reliable answer rather than guessing.
                  </div>
                </div>
              </div>

              <div class="accordion-item faq-item">
                <h3 class="accordion-header">
                  <button class="accordion-button collapsed faq-button" type="button" data-bs-toggle="collapse"
                    data-bs-target="#sfaq3">
                    Can scalp psoriasis and seborrheic dermatitis happen at the same time?
                  </button>
                </h3>
                <div id="sfaq3" class="accordion-collapse collapse" data-bs-parent="#scalpFAQ">
                  <div class="accordion-body faq-body">
                    Yes, this overlap is called sebopsoriasis, and it combines features of both conditions. It can look different on darker skin tones than the redness typically described in general information, which is why an in person assessment matters more than comparing your scalp to a generic description online.
                  </div>
                </div>
              </div>

              <div class="accordion-item faq-item">
                <h3 class="accordion-header">
                  <button class="accordion-button collapsed faq-button" type="button" data-bs-toggle="collapse"
                    data-bs-target="#sfaq4">
                    Can scalp psoriasis ever go away completely?
                  </button>
                </h3>
                <div id="sfaq4" class="accordion-collapse collapse" data-bs-parent="#scalpFAQ">
                  <div class="accordion-body faq-body">
                    Scalp psoriasis is a chronic autoimmune condition, so it tends to follow a pattern of flares and remission rather than disappearing permanently. Treatment focuses on controlling flares and extending remission periods rather than promising a permanent cure.
                  </div>
                </div>
              </div>

              <div class="accordion-item faq-item">
                <h3 class="accordion-header">
                  <button class="accordion-button collapsed faq-button" type="button" data-bs-toggle="collapse"
