                <p class="small text-muted">Botox is one of the most well-known anti-ageing treatments for dynamic wrinkles — those caused by facial muscle movements. It relaxes the muscles responsible for frown lines, forehead lines, and crow's feet, giving the skin a smoother appearance. Results typically last 3 to 6 months.</p>
