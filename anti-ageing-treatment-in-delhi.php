              </div>
              <div class="timeline-lux-item" data-step="">
                <h4 class="h6 fw-bold mb-1">Chemical Peels for Skin Renewal</h4>
                <p class="small text-muted">Medical-grade chemical peels remove the outermost layers of dull, damaged skin to reveal fresher, more even skin underneath. They are effective for addressing fine lines, pigmentation, and overall skin texture. Different strengths are used depending on your skin's needs.</p>
