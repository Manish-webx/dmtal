                <p class="small text-muted">Laser treatments stimulate collagen production and address pigmentation, sun damage, and skin laxity. At Dermatales, laser therapies are carefully chosen based on your skin tone and concern. This includes Q-switched and fractional laser options for skin brightening and resurfacing.</p>
              </div>
              <div class="timeline-lux-item" data-step="">
                <h4 class="h6 fw-bold mb-1">Microneedling with Radiofrequency (RF)</h4>
                <p class="small text-muted">This procedure uses tiny needles combined with radiofrequency energy to trigger the skin's natural collagen and elastin production. It is particularly effective for improving skin firmness, reducing fine lines, and refining skin texture without surgery.</p>
              </div>
              <div class="timeline-lux-item" data-step="">
                <h4 class="h6 fw-bold mb-1">PRP Therapy (Platelet-Rich Plasma)</h4>
                <p class="small text-muted">PRP therapy — often called the 'vampire facial' — uses your own blood's growth factors to stimulate skin renewal. It helps improve skin quality, reduce fine lines, and give the skin a healthier, more youthful appearance. It is completely natural and uses no synthetic substances.</p>
              </div>
              <div class="timeline-lux-item" data-step="">
                <h4 class="h6 fw-bold mb-1">Skin Boosters and Hydration Therapy</h4>
                <p class="small text-muted">Skin boosters are injectable treatments that deliver deep hydration directly into the skin. They improve skin quality, glow, and elasticity from within — particularly useful for skin that looks tired or dehydrated despite a good skincare routine.</p>
